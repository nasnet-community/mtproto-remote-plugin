import type { Page } from '@playwright/test'
import { FRA, HEL, alertDialog, dialog, expect, hexOf, openServer, test, toast } from './fixtures'

async function aliceLink(page: Page) {
  await page.getByRole('tab', { name: 'Users' }).click()
  const alice = page.getByRole('row').filter({ has: page.getByText('alice', { exact: true }) })
  await alice.getByRole('button', { name: 'Share' }).click()
  const share = dialog(page, "Share alice's proxy")
  const link = (await share.locator('[data-link]').textContent()) ?? ''
  await share.getByRole('button', { name: 'Close' }).click()
  return link
}

const allowlist = (page: Page) => page.locator('section', { has: page.getByRole('heading', { name: 'Telegram allowlist' }) })

test('changing the cover site checks it, says every link changes, then saves', async ({ page }) => {
  await openServer(page, FRA)
  expect(await aliceLink(page)).toContain(hexOf('www.example.com'))
  await page.getByRole('tab', { name: 'Settings' }).click()
  await expect(page).toHaveURL(/#\/servers\/1\/settings$/)
  await page.getByRole('button', { name: 'Change cover site…' }).click()
  const d = dialog(page, 'Change cover site')
  await expect(d).toContainText('Frankfurt VPS uses www.example.com now.')
  const use = d.getByRole('button', { name: /^Use / })
  await expect(d.getByRole('button', { name: 'Check' })).toBeDisabled()
  await d.getByLabel('New cover site').fill('bad.example.net')
  await d.getByRole('button', { name: 'Check' }).click()
  await expect(d).toContainText("bad.example.net doesn't work as a cover site")
  await expect(d).toContainText('bad.example.net does not offer TLS 1.3')
  await expect(use).toBeDisabled()
  await expect(d).not.toContainText('get new links')

  await d.getByLabel('New cover site').fill('learn.example.net')
  await expect(use).toBeDisabled()
  await d.getByRole('button', { name: 'Check' }).click()
  await expect(d).toContainText('Works as a cover site, tested from the server')
  await expect(d).toContainText('Resolves to 192.0.2.10, 2001:db8::10, 38 ms from the server.')
  await expect(d).toContainText("All 22 users get new links. Their old links stop working, so you'll need to share the new ones.")
  await expect(d.getByRole('button', { name: 'Check again' })).toBeVisible()
  await d.getByRole('button', { name: 'Use learn.example.net' }).click()
  await expect(toast(page, 'Cover site is now learn.example.net')).toBeVisible()
  await expect(d).toBeHidden()
  expect(await aliceLink(page)).toContain(hexOf('learn.example.net'))
})

test('sets the connection limit with a slider within the budget, and asks before saving', async ({ page }) => {
  await openServer(page, FRA, 'settings')
  const main = page.locator('main')
  const slider = page.getByRole('slider', { name: /Connection limit/ })
  await expect(slider).toHaveValue('2000')
  await expect(slider).toHaveAttribute('max', '3500')
  await expect(main).toContainText('3,500 (what this router has free for it)')
  await expect(main).toContainText('This server 2,000')
  await expect(main).toContainText('Helsinki ARM 1,500')
  await expect(main).toContainText('Amsterdam backup 1,000')
  await expect(main).toContainText('Free 1,500 of 6,000')
  const save = page.getByRole('button', { name: 'Save…' })
  await expect(save).toBeDisabled()

  await slider.focus()
  for (let i = 0; i < 5; i++) await page.keyboard.press('ArrowRight')
  await expect(slider).toHaveValue('2500')
  await expect(page.getByText('Unsaved: 2,000 → 2,500')).toBeVisible()
  await expect(main).toContainText('Free 1,000 of 6,000')
  // Enter no longer saves
  await page.keyboard.press('Enter')
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Discard' }).click()
  await expect(slider).toHaveValue('2000')
  await expect(page.getByText(/^Unsaved/)).toHaveCount(0)

  await slider.focus()
  await page.keyboard.press('End')
  await expect(slider).toHaveValue('3500')
  await save.click()
  const confirm = alertDialog(page, 'Save the connection limit?')
  await expect(confirm).toContainText('open connections drop, from 6 people online.')
  await expect(confirm).toContainText('Frankfurt VPS can then hold 3,500 connections at once.')
  await confirm.getByRole('button', { name: 'Save and reconnect' }).click()
  await expect(toast(page, 'Connection limit set to 3,500')).toBeVisible()
  await expect(page.getByText(/^Unsaved/)).toHaveCount(0)
  await expect(page.getByRole('slider', { name: /Connection limit/ })).toHaveValue('3500')
})

test('leaving with an unsaved limit asks first, the back button too', async ({ page }) => {
  await openServer(page, FRA)
  await page.getByRole('tab', { name: 'Settings' }).click()
  const slider = page.getByRole('slider', { name: /Connection limit/ })
  await slider.focus()
  await page.keyboard.press('ArrowRight')
  await page.getByRole('tab', { name: 'Users' }).click()
  const ask = alertDialog(page, 'Leave without saving?')
  await expect(ask).toContainText("The connection limit (2,000 → 2,100) isn't saved.")
  await ask.getByRole('button', { name: 'Cancel' }).click()
  await expect(page).toHaveURL(/settings$/)
  await expect(slider).toHaveValue('2100')

  await page.goBack()
  await expect(ask).toBeVisible()
  await expect(page).toHaveURL(/settings$/)
  await ask.getByRole('button', { name: 'Discard and leave' }).click()
  await expect(page).toHaveURL(/#\/servers\/1$/)
  await expect(page.getByRole('tab', { name: 'Users' })).toHaveAttribute('aria-selected', 'true')
})

test('changes the link port with a job; a port that fails moves back', async ({ page }) => {
  await openServer(page, FRA, 'settings')
  await expect(page.locator('main')).toContainText('Link port 8443 · 2 of 2 connections up')
  await page.getByRole('button', { name: 'Change link port…' }).click()
  const d = dialog(page, 'Change the link port')
  await expect(d).toContainText('Frankfurt VPS links on port 8443 now.')
  const port = d.getByLabel('New link port')
  await port.fill('8443')
  await expect(port).toHaveAccessibleDescription('That is the port it uses now.')
  await expect(d.getByRole('button', { name: 'Change port' })).toBeDisabled()
  await port.fill('9999')
  await d.getByRole('button', { name: 'Change port' }).click()
  const failed = dialog(page, /Link port change failed/)
  await expect(failed).toBeVisible({ timeout: 10000 })
  await expect(failed).toContainText('the link did not come up on port 9999; it is back on 8443')
  await expect(toast(page, 'Link port change failed')).toBeVisible()
  await failed.getByRole('button', { name: 'Done' }).click()

  await page.getByRole('button', { name: 'Change link port…' }).click()
  await d.getByLabel('New link port').fill('9000')
  await d.getByRole('button', { name: 'Change port' }).click()
  const job = dialog(page, /Changing the link port|Link port changed/)
  await expect(job).toContainText('Move the link over')
  await expect(dialog(page, /Link port changed/)).toBeVisible({ timeout: 10000 })
  await expect(toast(page, 'Link port changed')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('main')).toContainText('Link port 9000')
})

test('advanced proxy options: names checked before they are added, and a restart asked for', async ({ page }) => {
  await openServer(page, FRA, 'settings')
  const open = page.getByRole('button', { name: /Advanced proxy options/ })
  await expect(open).toHaveAttribute('aria-expanded', 'false')
  await open.click()
  const add = page.getByLabel('Add a cover name')
  await add.fill('bad.example.net')
  await page.getByRole('button', { name: 'Check and add' }).click()
  await expect(page.locator('main')).toContainText('bad.example.net does not offer TLS 1.3')
  await expect(page.getByRole('button', { name: 'Remove bad.example.net' })).toHaveCount(0)
  await add.fill('www.example.com')
  await expect(page.locator('main')).toContainText('That is the main cover site.')
  await add.fill('cdn.example.com')
  await page.getByRole('button', { name: 'Check and add' }).click()
  await expect(page.getByRole('button', { name: 'Remove cdn.example.com' })).toBeVisible()
  await expect(add).toHaveValue('')
  await page.getByLabel('Device window').fill('30')
  await page.getByLabel('Proxy log level').selectOption({ label: 'Verbose' })
  await page.getByRole('button', { name: 'Save options' }).click()
  const confirm = alertDialog(page, 'Save and restart the proxy?')
  await expect(confirm).toContainText('open connections drop')
  await confirm.getByRole('button', { name: 'Save and restart' }).click()
  await expect(toast(page, 'Proxy options saved')).toBeVisible()

  await page.reload()
  await page.getByRole('button', { name: /Advanced proxy options/ }).click()
  await expect(page.getByRole('button', { name: 'Remove cdn.example.com' })).toBeVisible()
  await expect(page.getByLabel('Device window')).toHaveValue('30')
  await expect(page.getByLabel('Proxy log level')).toHaveValue('verbose')
  // the device window alone doesn't restart the proxy, so it saves without asking
  await page.getByLabel('Device window').fill('60')
  await page.getByRole('button', { name: 'Save options' }).click()
  await expect(toast(page, 'Proxy options saved')).toBeVisible()
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await page.getByLabel('Device window').fill('99999')
  await expect(page.getByLabel('Device window')).toHaveAccessibleDescription('Use 0 to 86,400 seconds.')
  await expect(page.getByRole('button', { name: 'Save options' })).toBeDisabled()
})

test('shows and refreshes the allowlist', async ({ page }) => {
  await openServer(page, FRA, 'settings')
  const card = allowlist(page)
  await expect(card).toContainText('1 prefix')
  await expect(card).toContainText("doesn't carry real Telegram traffic yet.")
  await expect(card).toContainText('never')
  await card.getByRole('button', { name: 'Refresh now' }).click()
  await expect(toast(page, 'Allowlist refreshed: 12 prefixes')).toBeVisible()
  await expect(card).toContainText('12 prefixes')
  await expect(card).not.toContainText('never')
})

test('a failed refresh shows the error on the card, and its toast stays until closed', async ({ page, request }) => {
  await request.post('/api/__reset', { data: { allowlistFails: true } })
  await openServer(page, FRA, 'settings')
  const card = allowlist(page)
  await expect(card).toContainText('never')
  await card.getByRole('button', { name: 'Refresh now' }).click()
  const err = toast(page, "Couldn't refresh the allowlist. lists.example.net did not answer within 20 s. The router keeps the 1 prefix it has.")
  await expect(err).toBeVisible()
  await expect(err).toHaveAttribute('role', 'alert')
  await expect(card.getByRole('alert')).toContainText('lists.example.net did not answer within 20 s')
  await expect(card).toContainText('just now')
  // an error stays put
  await page.waitForTimeout(4500)
  await expect(err).toBeVisible()
  await err.getByRole('button', { name: 'Dismiss' }).click()
  await expect(err).toHaveCount(0)
})

